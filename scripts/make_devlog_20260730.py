normal.font.name = "맑은 고딕"
normal.font.size = Pt(10.5)
normal._element.rPr.rFonts.set(qn("w:eastAsia"), "맑은 고딕")

BLUE = RGBColor(0x1F, 0x6F, 0xEB)
RED = RGBColor(0xC0, 0x39, 0x2B)
GRAY = RGBColor(0x55, 0x55, 0x55)
GREEN = RGBColor(0x1E, 0x7E, 0x34)
MONO = RGBColor(0x24, 0x29, 0x2E)


def h1(t):
    doc.add_heading(t, level=1)


def h2(t):
    doc.add_heading(t, level=2)


def p(t, bold=False):
    para = doc.add_paragraph()
    r = para.add_run(t)
    r.bold = bold
    return para


def bullet(t):
    doc.add_paragraph(t, style="List Bullet")


def analogy(t):
    para = doc.add_paragraph()
    r = para.add_run("🔎 비유   ")
    r.bold = True
    r.font.color.rgb = BLUE
    r2 = para.add_run(t)
    r2.font.color.rgb = BLUE
    para.paragraph_format.left_indent = Pt(12)


def field(label, text, color=GRAY):
    para = doc.add_paragraph()
    para.paragraph_format.left_indent = Pt(12)
    r = para.add_run(f"{label}  ")
    r.bold = True
    r.font.color.rgb = color
    para.add_run(text)
    return para


def note(t):
    para = doc.add_paragraph()
    r = para.add_run("🛠 전문가 노트   ")
    r.bold = True
    r.font.color.rgb = GREEN
    r2 = para.add_run(t)
    r2.font.color.rgb = GREEN
    para.paragraph_format.left_indent = Pt(12)


def warn(t):
    para = doc.add_paragraph()
    r = para.add_run("⚠️ 함정   ")
    r.bold = True
    r.font.color.rgb = RED
    r2 = para.add_run(t)
    r2.font.color.rgb = RED
    para.paragraph_format.left_indent = Pt(12)


def ev(title, lines):
    """터미널 증거 — 실제로 화면에 찍힌 문자열."""
    cap = doc.add_paragraph()
    cap.paragraph_format.left_indent = Pt(12)
    cap.paragraph_format.space_after = Pt(2)
    r = cap.add_run(f"▶ 실제 출력 — {title}")
    r.bold = True
    r.font.size = Pt(9.5)
    r.font.color.rgb = GRAY

    for line in lines:
        para = doc.add_paragraph()
        para.paragraph_format.left_indent = Pt(18)
        para.paragraph_format.space_after = Pt(0)
        para.paragraph_format.space_before = Pt(0)
        para.alignment = WD_ALIGN_PARAGRAPH.LEFT
        run = para.add_run(line if line else " ")
        run.font.name = "Consolas"
        run.font.size = Pt(9)
        run.font.color.rgb = MONO
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Consolas")
    doc.add_paragraph("").paragraph_format.space_after = Pt(2)



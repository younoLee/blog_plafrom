def write_tags_json() -> Path:
    """POSTS를 gen-static.mjs가 읽을 수 있는 모양으로 내보낸다.

    날짜를 키로 둔다 — 정적 페이지의 파일명이 날짜라(`content/devlog/2026-08-14.md`)
    Node 쪽이 파일명만으로 맞출 수 있다. 제목도 같이 넣어 두면 표가 어긋났을 때
    (마크다운 H1 ≠ POSTS 제목) 빌드가 알아챌 수 있다.
    """
    payload = {
        date: {"title": title, "tags": tags} for date, (title, tags) in sorted(POSTS.items())
    }
    TAGS_JSON.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return TAGS_JSON


